def test_discovers_generated_image(tmp_path: Path) -> None:
    """An image explicitly generated by source code should be discovered."""
    _write_source(
        tmp_path,
        """
from pathlib import Path
import matplotlib.pyplot as plt

IMAGE_PATH = Path("docs") / "images" / "sales_by_region.png"

fig, ax = plt.subplots()
fig.savefig(IMAGE_PATH)
""",
    )

    paths = discover_generated_paths(tmp_path)

    assert paths == (Path("docs/images/sales_by_region.png"),)


def test_does_not_infer_other_images_in_same_directory(
    tmp_path: Path,
) -> None:
    """Only the exact image generated by source code should be discovered."""
    generated_image = tmp_path / "docs" / "images" / "sales_by_region.png"
    preserved_image = tmp_path / "docs" / "images" / "Fig1.png"

    generated_image.parent.mkdir(parents=True)

    generated_image.write_bytes(b"generated")
    preserved_image.write_bytes(b"preserved")

    _write_source(
        tmp_path,
        """
from pathlib import Path
import matplotlib.pyplot as plt

IMAGE_PATH = Path("docs") / "images" / "sales_by_region.png"

fig, ax = plt.subplots()
fig.savefig(IMAGE_PATH)
""",
    )

    paths = discover_generated_paths(tmp_path)

    assert Path("docs/images/sales_by_region.png") in paths
    assert Path("docs/images/Fig1.png") not in paths


def test_does_not_treat_read_path_as_generated(tmp_path: Path) -> None:
    """Input data read by the source should not be considered generated."""
    _write_source(
        tmp_path,
        """
from pathlib import Path
import pandas as pd

INPUT_PATH = Path("data") / "prepared" / "sales.csv"

df = pd.read_csv(INPUT_PATH)
""",
    )

    paths = discover_generated_paths(tmp_path)

    assert paths == ()


def test_input_and_output_paths_are_distinguished(tmp_path: Path) -> None:
    """The source operation, not the directory name, determines provenance."""
    _write_source(
        tmp_path,
        """
from pathlib import Path
import pandas as pd

INPUT_PATH = Path("data") / "prepared" / "sales.csv"
OUTPUT_PATH = Path("data") / "dw" / "sales.parquet"

df = pd.read_csv(INPUT_PATH)
df.to_parquet(OUTPUT_PATH)
""",
    )

    paths = discover_generated_paths(tmp_path)

    assert paths == (Path("data/dw/sales.parquet"),)


def test_dynamic_output_path_is_not_guessed(tmp_path: Path) -> None:
    """A path that cannot be resolved statically should not be returned."""
    _write_source(
        tmp_path,
        """
from pathlib import Path
import pandas as pd

name = get_output_name()
OUTPUT_PATH = Path("data") / "prepared" / f"{name}.csv"

df = pd.DataFrame({"value": [1, 2, 3]})
df.to_csv(OUTPUT_PATH, index=False)
""",
    )

    paths = discover_generated_paths(tmp_path)

    assert paths == ()


def test_returns_empty_tuple_without_src_directory(tmp_path: Path) -> None:
    """A repository without src should have no discovered source outputs."""
    paths = discover_generated_paths(tmp_path)

    assert paths == ()
