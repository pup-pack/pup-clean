"""Tests for generated artifact source inspection."""

from pathlib import Path

from pup_clean.inspect.generated import discover_generated_paths


def _write_source(root: Path, source: str) -> None:
    """Write a Python source file under the repository src directory."""
    package_dir = root / "src" / "example_project"
    package_dir.mkdir(parents=True)

    (package_dir / "main.py").write_text(
        source,
        encoding="utf-8",
    )


def test_discovers_generated_csv_literal_path(tmp_path: Path) -> None:
    """A CSV written by project source should be discovered."""
    _write_source(
        tmp_path,
        """
import pandas as pd

df = pd.DataFrame({"value": [1, 2, 3]})
df.to_csv("data/prepared/results.csv", index=False)
""",
    )

    paths = discover_generated_paths(tmp_path)

    assert paths == (Path("data/prepared/results.csv"),)


def test_discovers_generated_path_from_path_objects(tmp_path: Path) -> None:
    """Path constants and slash composition should be resolved."""
    _write_source(
        tmp_path,
        """
from pathlib import Path

import pandas as pd

DATA_DIR = Path("data")
PREPARED_DIR = DATA_DIR / "prepared"
OUTPUT_PATH = PREPARED_DIR / "sales_prepared.parquet"

df = pd.DataFrame({"value": [1, 2, 3]})
df.to_parquet(OUTPUT_PATH)
""",
    )

    paths = discover_generated_paths(tmp_path)

    assert paths == (Path("data/prepared/sales_prepared.parquet"),)


